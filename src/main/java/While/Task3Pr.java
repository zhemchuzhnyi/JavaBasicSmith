package While;

public class Task3Pr {
    public static void main(String[] args) {
        int count = 0;

        while (count < 5) {
            System.out.println("Hello, World");
            count++;
        }

        count = 0;
        while (count < 7) {
            System.out.println("Привет, Мир");
            count++;
        }
    }
}
